-- 建立拍攝小組資料表；只允許 Streamlit 伺服器端 service_role 存取
create table if not exists public.shooting_groups (
    id bigint generated by default as identity primary key,
    group_name text not null,
    location text,
    meeting_time text,
    members text,
    notes text,
    photo_path text,
    group_number integer,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
alter table public.shooting_groups enable row level security;
create unique index if not exists shooting_groups_group_number_unique on public.shooting_groups (group_number) where group_number is not null;

-- 刻意不建立 anon/authenticated policies。
-- Streamlit 伺服器端以 SUPABASE_SECRET_KEY 存取此表。

create or replace function public.verify_student_login(
    input_seat_no text,
    input_password text
)
returns table (id bigint, seat_no text, name text)
language sql
security definer
set search_path = ''
as $$
    select g.id, g.seat_no::text, g.name::text
    from public.grad_album as g
    where g.seat_no::text = input_seat_no
      and g.password_hash is not null
      and g.password_hash = extensions.crypt(input_password, g.password_hash)
    limit 1;
$$;

revoke all on function public.verify_student_login(text, text)
from public, anon, authenticated;
grant execute on function public.verify_student_login(text, text)
to service_role;
