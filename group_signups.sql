-- 小組登記資料：每位學生只能登記一次，登記編號由 identity 按新增順序自動產生。
-- 僅由 Streamlit 伺服器端使用 SUPABASE_SECRET_KEY 存取；不開放 anon/authenticated。
create table if not exists public.group_signups (
    id bigint generated by default as identity primary key,
    student_id bigint not null unique references public.grad_album(id) on delete cascade,
    seat_no text not null,
    student_name text not null,
    assigned_group integer,
    created_at timestamptz not null default now(),
    constraint group_signups_assigned_group_positive
        check (assigned_group is null or assigned_group > 0)
);

alter table public.group_signups enable row level security;

-- 刻意不建立 anon/authenticated policies。
-- 登記順序以 id 遞增為準；分組人數不設固定上限。
